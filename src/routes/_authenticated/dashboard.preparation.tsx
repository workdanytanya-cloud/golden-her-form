function ArticleCard({ article }: { article: Article }) {
  const [open, setOpen] = useState(false);
  return (
    <div className="overflow-hidden rounded-2xl border border-gold/15 bg-surface/40">
      <button
        type="button"
        onClick={() => setOpen((v) => !v)}
        className="flex w-full items-start gap-4 p-5 text-left transition-colors hover:bg-surface/60"
        aria-expanded={open}
      >
        <div className="rounded-xl bg-gold/15 p-3 text-gold">{article.icon}</div>
        <div className="flex-1 min-w-0">
          <p className="font-display text-lg text-ivory">{article.title}</p>
          <p className="mt-1 text-sm text-warm-gray">{article.lead}</p>
        </div>
        <ChevronDown
          className={`mt-1 h-5 w-5 shrink-0 text-warm-gray transition-transform ${
            open ? "rotate-180 text-gold" : ""
          }`}
        />
      </button>
      {open && (
        <div className="space-y-3 border-t border-gold/10 px-5 pb-6 pt-4 text-sm leading-relaxed text-warm-gray md:text-[15px]">
          {article.body}
        </div>
      )}
    </div>
  );
}

