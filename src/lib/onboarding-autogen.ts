/**
 * After a client submits the onboarding questionnaire, generate DRAFT
 * training program and nutrition plan from their answers.
 *
 * Персонализация: профиль клиента + safety gate + валидация (см. src/lib/personalization).
 * LLM не считает калории/БЖУ — только calcTargets() и generatePlan().
 */
