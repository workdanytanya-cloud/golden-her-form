export const ALL_DIET_OPTIONS: DietOption[] = [...LIFESTYLE_DIETS, ...MEDICAL_DIET_TABLES];

export function findDietOption(value: string | null | undefined): DietOption | undefined {
  if (!value) return undefined;
  return ALL_DIET_OPTIONS.find((d) => d.value === value);
}

/** Подпись для админки: «Стол №1 — …» */
export function formatDietLabel(value: string | null | undefined): string | null {
  if (!value) return null;
  const opt = findDietOption(value);
  if (!opt) return value;
  if (MEDICAL_DIET_TABLES.some((d) => d.value === opt.value)) {
    return `${opt.value} (${opt.indication})`;
  }
  return opt.value;
}
