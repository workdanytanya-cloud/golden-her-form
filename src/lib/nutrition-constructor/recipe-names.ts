const TECHNICAL_NAME =
  /небольш|немного|мал(?:ое|ым|ой|ого)?\s+количество|л[её]гк[а-яё]*\s+порц|больш[а-яё]*\s+порц|плотн[а-яё]*\s+порц|остаток|добор|вариант\s*№|вариант\s+\d|\b[0-9a-f]{8}-[0-9a-f]{4}-/i;

export function technicalNameReason(name: string): string | null {
  const text = name.trim();
  if (!text) return "Пустое название";
  if (TECHNICAL_NAME.test(text)) {
    return "Название описывает размер порции или служебный идентификатор";
  }
  return null;
}

export function repairRecipeName(name: string): string {
  const exact = EXACT_NAMES[name.trim()];
  if (exact) return exact;
  return name
    .replace(/\s+с\s+небольш\w+\s+/gi, " с ")
    .replace(/\s+небольш\w+/gi, "")
    .replace(/,\s*плотн\w+\s+порция/gi, "")
    .replace(/\s{2,}/g, " ")
    .trim();
}
