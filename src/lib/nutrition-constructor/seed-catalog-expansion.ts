type Ing =
  | [string, number, number, number]
  | [string, number, number, number, { required?: boolean; scalable?: boolean }];

function ings(list: Ing[]): ExpandedSeedIngredient[] {
  return list.map((row) => {
    const [product_slug, min_g, max_g, default_g, flags] = row;
    return {
      product_slug,
      min_g,
      max_g,
      default_g,
      required: flags?.required ?? true,
      scalable: flags?.scalable ?? true,
    };
  });
}

function main(
  slug: string,
  name: string,
  meal_types: MealRole[],
  ingredientRows: Ing[],
  steps: string[],
  prep = 20,
  extra: Partial<ExpandedSeedRecipe> = {},
): ExpandedSeedRecipe {
  return r({
    slug,
    name,
    meal_type: "main",
    meal_types,
    requires_cooking: true,
    prep_time_min: prep,
    weighing_note: "Крупы и мясо/рыбу взвешивать до приготовления.",
    steps,
    ingredients: ings(ingredientRows),
    ...extra,
  });
}

function snack(
  slug: string,
  name: string,
  ingredientRows: Ing[],
  steps: string[],
  requiresCooking = false,
  prep = 5,
  extra: Partial<ExpandedSeedRecipe> = {},
): ExpandedSeedRecipe {
  return r({
    slug,
    name,
    meal_type: "snack",
    meal_types: ["snack"],
    requires_cooking: requiresCooking,
    prep_time_min: prep,
    weighing_note: "Взвешивать порции как указано.",
    steps,
    ingredients: ings(ingredientRows),
    batch_friendly: false,
    ...extra,
  });
}

