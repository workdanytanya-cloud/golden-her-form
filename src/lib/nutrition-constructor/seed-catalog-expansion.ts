import type { SeedProduct, SeedRecipe } from "@/lib/nutrition-constructor/seed-data";
import type { CookingMethod, MealRole } from "@/lib/nutrition-constructor/recipe-variety";

export type ExpandedSeedProduct = SeedProduct & {
  allergen_tags?: string[];
  lactose_free?: boolean;
  gluten_free?: boolean;
  vegetarian?: boolean;
  food_tags?: string[];
};

export type ExpandedSeedIngredient = {
  product_slug: string;
  min_g: number;
  max_g: number;
  default_g: number;
  required?: boolean;
  scalable?: boolean;
};

export type ExpandedSeedRecipe = Omit<SeedRecipe, "ingredients"> & {
  meal_types: MealRole[];
  variant_group?: string;
  ingredient_signature?: string;
  primary_protein?: string;
  primary_carb?: string;
  cooking_method?: CookingMethod;
  difficulty?: "easy" | "medium";
  active_time_minutes?: number;
  total_time_minutes?: number;
  batch_friendly?: boolean;
  storage_notes?: string;
  dietary_tags?: string[];
  allergens?: string[];
  min_servings?: number;
  max_servings?: number;
  ingredients: ExpandedSeedIngredient[];
};

function p(partial: ExpandedSeedProduct): ExpandedSeedProduct {
  return partial;
}

function r(partial: ExpandedSeedRecipe): ExpandedSeedRecipe {
  return {
    difficulty: "easy",
    batch_friendly: partial.batch_friendly ?? partial.requires_cooking,
    min_servings: partial.min_servings ?? 1,
    max_servings: partial.max_servings ?? 2,
    active_time_minutes: partial.active_time_minutes ?? Math.min(partial.prep_time_min, 20),
    total_time_minutes: partial.total_time_minutes ?? partial.prep_time_min,
    storage_notes:
      partial.storage_notes ??
      (partial.requires_cooking
        ? "Хранить в холодильнике до 2 суток в закрытом контейнере."
        : "Собрать перед едой."),
    ...partial,
  };
}

