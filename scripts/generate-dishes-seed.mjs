function kcal(p, f, c) {
  return Math.round(p * 4 + c * 4 + f * 9);
}

function esc(s) {
  return String(s).replace(/'/g, "''");
}

function arr(a) {
  return `ARRAY[${a.map((x) => `'${esc(x)}'`).join(",")}]::text[]`;
}

function jsonb(v) {
  return `'${esc(JSON.stringify(v))}'::jsonb`;
}

/**
 * @typedef {{
 *   slug: string;
 *   name: string;
 *   meal: 'breakfast'|'lunch'|'dinner'|'snack';
 *   tags: string[];
 *   p: number; f: number; c: number;
 *   portion: number;
 *   description: string;
 *   ingredients: Array<{raw:string; raw_g:number; cooked_g:number}>;
 *   steps: string[];
 *   replacements?: string[];
 * }} DishDef
 */

/** @type {DishDef[]} */
const dishes = [];

function add(d) {
  const cal = kcal(d.p, d.f, d.c);
  // sanity: macros non-negative, portion reasonable
  if (d.p < 0 || d.f < 0 || d.c < 0) throw new Error(`Negative macro: ${d.slug}`);
  if (cal < 20 || cal > 600) throw new Error(`Odd kcal ${cal} for ${d.slug}`);
  dishes.push({ ...d, calories: cal });
}

function tableDish(table, meal, slugSuffix, name, macros, portion, description, ingredients, steps, extraTags = [], replacements = []) {
  add({
    slug: `t${table}-${meal}-${slugSuffix}`,
    name,
    meal,
    tags: [`table_${table}`, `стол_${table}`, ...extraTags],
    p: macros.p,
    f: macros.f,
    c: macros.c,
    portion,
    description,
    ingredients,
    steps,
    replacements,
  });
}

