const slugs = new Set();
for (const d of dishes) {
  if (slugs.has(d.slug)) throw new Error(`Duplicate slug: ${d.slug}`);
  slugs.add(d.slug);
  const expected = kcal(d.p, d.f, d.c);
  if (expected !== d.calories) throw new Error(`Kcal mismatch ${d.slug}`);
}

// Per-table meal coverage
for (let t = 1; t <= 15; t++) {
  const set = dishes.filter((d) => d.tags.includes(`table_${t}`));
  if (set.length < 3) throw new Error(`Table ${t} has only ${set.length} dishes`);
  const meals = new Set(set.map((d) => d.meal));
  for (const need of ["breakfast", "lunch", "dinner"]) {
    if (!meals.has(need)) throw new Error(`Table ${t} missing ${need}`);
  }
}

