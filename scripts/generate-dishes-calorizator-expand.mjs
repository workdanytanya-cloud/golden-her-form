const slugs = new Set();
for (const d of dishes) {
  if (slugs.has(d.slug)) throw new Error(`Duplicate slug: ${d.slug}`);
  slugs.add(d.slug);
}

for (let t = 1; t <= 15; t++) {
  const set = dishes.filter((d) => d.tags.includes(`table_${t}`));
  if (set.length < 4) throw new Error(`Table ${t} expected 4 new dishes, got ${set.length}`);
}

const lines = [];
lines.push(`-- Расширение библиотеки блюд по логике столов Певзнера (ориентир: calorizator.ru/diet/med).`);
