function kcal(p, f, c) {
  return Math.round(p * 4 + c * 4 + f * 9);
}
function esc(s) {
  return String(s).replace(/'/g, "''");
}
function arr(a) {
  return `ARRAY[${a.map((x) => `'${esc(x)}'`).join(",")}]::text[]`;
}
function jsonb(v) {
  return `'${esc(JSON.stringify(v))}'::jsonb`;
}

/** @type {any[]} */
const dishes = [];

function add(d) {
  const calories = kcal(d.p, d.f, d.c);
  if (d.p < 0 || d.f < 0 || d.c < 0) throw new Error(`Negative macro: ${d.slug}`);
  if (calories < 20 || calories > 600) throw new Error(`Odd kcal ${calories} for ${d.slug}`);
  dishes.push({ ...d, calories });
}

function tableDish(table, meal, slugSuffix, name, macros, portion, description, ingredients, steps, extraTags = [], replacements = []) {
  add({
    slug: `t${table}-${meal}-${slugSuffix}`,
    name,
    meal,
    tags: [`table_${table}`, `стол_${table}`, ...extraTags],
    p: macros.p,
    f: macros.f,
    c: macros.c,
    portion,
    description,
    ingredients,
    steps,
    replacements,
  });
}

function gen(meal, slugSuffix, name, macros, portion, description, ingredients, steps, extraTags = [], replacements = []) {
  add({
    slug: `gen-${meal}-${slugSuffix}`,
    name,
    meal,
    tags: ["general", ...extraTags],
    p: macros.p,
    f: macros.f,
    c: macros.c,
    portion,
    description,
    ingredients,
    steps,
    replacements,
  });
}

